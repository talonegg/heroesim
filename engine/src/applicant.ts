/**
 * Recruitment (E4): people turn up asking for work, wait a while, and go away again if
 * nobody takes them on. How good they are is what the Guild's Standing has earned, and
 * that is the only thing Standing does — Regard gets you work, Standing gets you people,
 * and no Commission, fee or Board decision reads it (CONTEXT · Standing).
 *
 * **Where the randomness comes from.** A batch draws from a stream of its own, seeded
 * from the Career's seed and the Day, exactly as `startingAge` seeds one from the seed
 * and a Hero's id (DL-16 §1, DL-19 §1). Nothing here touches `career.rng`. So arrival is
 * deterministic from the seed, a batch cannot shift the Beats of a Commission resolving
 * the same Day, and ignoring an Applicant cannot change how anything else unfolds.
 */

import { startingAge } from './age.js';
import { cloneCareer } from './clone.js';
import { clamp } from './config.js';
import type { Content } from './content.js';
import { EngineError } from './errors.js';
import type { GameEvent } from './events.js';
import {
  applicantFee,
  calibreOfStats,
  calibreStatBudget,
  distributeStats,
  freeName,
  maxCalibreFor,
  namesInUse,
  PRONOUNS,
  statTotal,
} from './people.js';
import { moveHero } from './rival.js';
import { rngOn, seedRng, type Rng } from './rng.js';
import { changeCoin, standingOf } from './state.js';
import type { Applicant, Calibre, Career, Hero, HeroTrait, Step } from './types.js';

/**
 * Re-exported where E4 put them. The definitions moved to `people.ts` in E5, so that a
 * Rival's Roster can be priced and generated by the same rules without `rival.ts` and
 * `applicant.ts` importing one another (DL-19 §8's four pure helpers are unchanged).
 */
export { applicantFee, calibreOfStats, calibreStatBudget };

/** Why a newly taken-on Hero thinks what they think of the Guildmaster. */
export const REASON_TAKEN_ON = 'you took them on';
/** Why somebody who once walked out thinks what they think of the Guildmaster again. */
export const REASON_CAME_BACK = 'they came back, and have not forgotten why they left';

/**
 * Why an Applicant cannot be taken on today. It is the very `EngineErrorCode`
 * {@link acceptApplicant} would throw, so a front end can hand it straight to
 * `errorSentence` without deciding for itself what "full" or "cannot pay" means (DL-19 §8).
 */
export type AcceptRefusalCode =
  | 'CareerEnded'
  | 'NoSuchApplicant'
  | 'RosterFull'
  | 'InsufficientCoin';

/** One reason an Applicant cannot be taken on, with the number that would answer it. */
export interface AcceptRefusal {
  code: AcceptRefusalCode;
  /** Coin still needed. Set only when the code is `InsufficientCoin`. */
  shortfall?: number;
}

/** One Applicant as a front end offers them: the person, the clock and the refusal. */
export interface ApplicantOffer {
  applicant: Applicant;
  /** Days until they give up waiting. One on the Day before they go; never below zero. */
  daysLeft: number;
  /** Why they cannot be taken on today, or absent when they can. */
  refusal?: AcceptRefusal;
}

/**
 * The best calibre this Guild's Standing reaches. High Standing widens the range a batch
 * draws from rather than guaranteeing the top of it (E4-S1).
 */
export function maxCalibre(career: Career): Calibre {
  const standing = standingOf(career);
  return maxCalibreFor(standing, career.config);
}

/** An Applicant currently waiting, by id. Expired ones are gone and are not searched. */
export function applicantById(career: Career, id: string): Applicant | undefined {
  return career.applicants.find((applicant) => applicant.id === id);
}

/**
 * Why this Applicant cannot be taken on today, or `undefined` when they can (DL-19 §8).
 * Read-only: it touches nothing and is safe to ask after every keypress.
 */
export function acceptRefusal(career: Career, applicantId: string): AcceptRefusal | undefined {
  if (career.ended !== undefined) return { code: 'CareerEnded' };
  const applicant = applicantById(career, applicantId);
  if (applicant === undefined) return { code: 'NoSuchApplicant' };
  if (career.guild.roster.length >= career.config.rosterCap) return { code: 'RosterFull' };
  if (career.guild.coin < applicant.askingFee) {
    return { code: 'InsufficientCoin', shortfall: applicant.askingFee - career.guild.coin };
  }
  return undefined;
}

/** Every Applicant currently waiting, with their clock and their refusal (DL-19 §8). */
export function applicantOffers(career: Career): ApplicantOffer[] {
  return career.applicants.map((applicant) => {
    const refusal = acceptRefusal(career, applicant.id);
    const offer: ApplicantOffer = {
      applicant,
      daysLeft: Math.max(0, applicant.expiresOn - career.day),
    };
    if (refusal !== undefined) offer.refusal = refusal;
    return offer;
  });
}

/** How often Applicants arrive as the Roster stands: sooner while it is short-handed. */
export function applicantInterval(career: Career): number {
  return career.guild.roster.length < career.config.rosterFloor
    ? career.config.applicantsEveryDaysBelowFloor
    : career.config.applicantsEveryDays;
}

/** Whether a batch is due today. */
function batchDue(career: Career): boolean {
  const interval = applicantInterval(career);
  return interval > 0 && career.day % interval === 0;
}

/** The generator a batch draws from: the Career's seed and the Day, and nothing else. */
function applicantStream(seed: string, day: number): Rng {
  return rngOn({ rng: seedRng(`${seed}:applicants:${day}`) });
}

/** Every id anybody in this Career holds, so a fresh one can never land on top of it. */
function idsInUse(draft: Career): Set<string> {
  return new Set([
    ...draft.guild.roster.map((hero) => hero.id),
    ...draft.guild.formerHeroes.map((hero) => hero.id),
    ...draft.applicants.map((applicant) => applicant.id),
    // A Rival's people cannot collide with an `a<n>` by construction (E5 gives them
    // `<rivalId>h<n>`), but this set is the defence and a defence names everybody.
    ...draft.rivals.flatMap((rival) => rival.roster.map((hero) => hero.id)),
  ]);
}

/**
 * The next fresh Applicant id, `a<n>`, from the Career's own counter. Monotonic, so an id
 * is never reused even after an Applicant has expired; and defensive, so a document whose
 * counter has been tampered with still cannot mint an id somebody already holds (DL-19 §2).
 */
function takeApplicantId(draft: Career, taken: ReadonlySet<string>): string {
  let id = `a${draft.nextApplicantNumber}`;
  while (taken.has(id)) {
    draft.nextApplicantNumber += 1;
    id = `a${draft.nextApplicantNumber}`;
  }
  draft.nextApplicantNumber += 1;
  return id;
}

/** Somebody nobody has met: a name, a Background and its Traits, an age and Stats. */
function freshApplicant(
  draft: Career,
  content: Content,
  rng: Rng,
  ceiling: Calibre,
  taken: Set<string>,
  names: Set<string>,
): Applicant {
  const { config } = draft;
  // Left exactly as E4 drew it — `between` and not the single unconditional `float` a
  // Rival's Roster uses — because every pinned id and calibre in E4's suite is this draw
  // (DL-19 §1). The two streams are separate, so they need not agree.
  const calibre = clamp(rng.between(1, ceiling), 1, ceiling) as Calibre;
  const background = rng.pick(content.backgrounds);
  const id = takeApplicantId(draft, taken);
  // Every name anybody alive in this Career answers to, the people on a Rival's Roster and
  // the Guildmaster among them (DL-22 §1). One `pick` either way, so widening it moved the
  // names in E4's own suite and not one id, calibre, Stat or age.
  const name = freeName(content, config, rng, names);
  taken.add(id);
  names.add(name);
  return {
    id,
    name,
    pronouns: rng.pick(PRONOUNS),
    stats: distributeStats(calibreStatBudget(calibre, config), config, rng),
    background: background.name,
    traits: background.traits.map((trait) => ({ name: trait, since: draft.day })),
    // Derived from the seed and the id rather than drawn, so it is the same number on
    // every machine and the batch's own stream is not what decides it (DL-16 §1).
    age: startingAge(draft.seed, id, config),
    calibre,
    askingFee: applicantFee(calibre, config),
    arrivedOn: draft.day,
    expiresOn: draft.day + config.applicantLingerDays,
  };
}

/** A Trait as it comes back with somebody: the same Trait, or nothing if it healed. */
function traitsBroughtBack(hero: Hero, day: number): HeroTrait[] {
  const kept: HeroTrait[] = [];
  for (const trait of hero.traits) {
    // An Injury whose Day has passed healed while they were away. One that has not keeps
    // its original `liftsOn`, so they may join still carrying it (E4-S4).
    if (trait.liftsOn !== undefined && trait.liftsOn <= day) continue;
    // The keys are written in the order `clone.ts` writes them, and `kind` travels with
    // the Trait: a timed Trait that arrives without one is read as an Injury, so dropping
    // it here would hand a returner an Injury they never had (E6, DL-23 §10).
    const carried: HeroTrait = { name: trait.name, since: trait.since };
    if (trait.liftsOn !== undefined) carried.liftsOn = trait.liftsOn;
    if (trait.kind !== undefined) carried.kind = trait.kind;
    kept.push(carried);
  }
  return kept;
}

/**
 * Somebody who walked out, asking to come back (E4-S4). They keep the id they left with,
 * their Traits and their Scars, and their age is set explicitly to the age they left at
 * plus the whole years since — never re-derived, which would hand them the age they would
 * have *started* at (DL-17, DL-19 §6).
 */
function returningApplicant(draft: Career, former: Hero, ceiling: Calibre): Applicant {
  const { config } = draft;
  const gone = former.exit?.onDay ?? draft.day;
  const years = config.daysPerYear > 0 ? Math.floor((draft.day - gone) / config.daysPerYear) : 0;
  const calibre = clamp(calibreOfStats(statTotal(former.stats), config), 1, ceiling) as Calibre;
  return {
    id: former.id,
    name: former.name,
    pronouns: former.pronouns,
    stats: { ...former.stats },
    background: former.background,
    traits: traitsBroughtBack(former, draft.day),
    age: former.age + years,
    calibre,
    askingFee: applicantFee(calibre, config),
    arrivedOn: draft.day,
    expiresOn: draft.day + config.applicantLingerDays,
    formerHeroId: former.id,
  };
}

/**
 * The former Heroes who could come back today: they walked out, the cooldown has passed,
 * and they are not already standing in the Hall waiting for an answer. Death and
 * Retirement never return.
 */
function couldComeBack(draft: Career): Hero[] {
  const waiting = new Set(draft.applicants.map((applicant) => applicant.id));
  return draft.guild.formerHeroes.filter(
    (hero) =>
      hero.exit?.kind === 'departure' &&
      draft.day - hero.exit.onDay >= draft.config.returnCooldownDays &&
      !waiting.has(hero.id),
  );
}

/**
 * Whoever has given up waiting goes, on the exact Day their span is up. Runs at the start
 * of the Day, before anybody new arrives, so a fresh batch is never shown beside a stale
 * one (DL-19 §4).
 */
export function expireApplicants(draft: Career, events: GameEvent[]): void {
  const going = draft.applicants.filter((applicant) => applicant.expiresOn <= draft.day);
  if (going.length === 0) return;
  draft.applicants = draft.applicants.filter((applicant) => applicant.expiresOn > draft.day);
  for (const applicant of going) {
    events.push({
      type: 'ApplicantDeclined',
      day: draft.day,
      applicantId: applicant.id,
      name: applicant.name,
      reason: 'expired',
    });
  }
}

/**
 * A batch turns up, if one is due. Returners take their slots first, and the rest of the
 * batch is made from content; below the Roster floor a batch is always as large as it can
 * be and comes twice as often (E4-S2).
 */
export function arriveApplicants(draft: Career, content: Content, events: GameEvent[]): void {
  if (!batchDue(draft)) return;
  const { config } = draft;
  const rng = applicantStream(draft.seed, draft.day);
  const shortHanded = draft.guild.roster.length < config.rosterFloor;
  const size = Math.max(
    0,
    shortHanded ? config.applicantBatchMax : rng.between(config.applicantBatchMin, config.applicantBatchMax),
  );
  if (size === 0) return;

  const ceiling = maxCalibre(draft);
  const taken = idsInUse(draft);
  const names = namesInUse(draft, 'with-the-door');

  const arrived: Applicant[] = [];
  for (const former of couldComeBack(draft)) {
    if (arrived.length >= size) break;
    if (!rng.chance(config.returnAsApplicantChance)) continue;
    arrived.push(returningApplicant(draft, former, ceiling));
    taken.add(former.id);
    names.add(former.name);
  }
  while (arrived.length < size) {
    arrived.push(freshApplicant(draft, content, rng, ceiling, taken, names));
  }

  draft.applicants.push(...arrived);
  draft.ledger.applicantsSeen += arrived.length;
  // Every OFFER of a returner, whether or not it is ever taken (finding C7). `returners`
  // itself is counted where an offer is actually accepted, in `acceptApplicant` below.
  draft.ledger.returnersOffered += arrived.filter(
    (applicant) => applicant.formerHeroId !== undefined,
  ).length;
  events.push({
    type: 'ApplicantsArrived',
    day: draft.day,
    applicantIds: arrived.map((applicant) => applicant.id),
    calibres: arrived.map((applicant) => applicant.calibre),
    expiresOn: draft.day + config.applicantLingerDays,
  });
}

/**
 * Take an Applicant on. They become a Hero with the same id, the same name, Stats,
 * Traits, Background and age, and the fee is paid (E4-S3).
 *
 * Every rejection leaves the Career byte-identical to the one it was given: the copy is
 * taken after the checks, so nothing at all has moved when one of them throws.
 *
 * @throws EngineError `CareerEnded`, `NoSuchApplicant`, `RosterFull` or `InsufficientCoin`.
 */
export function acceptApplicant(career: Career, applicantId: string): Step {
  const refused = acceptRefusal(career, applicantId);
  if (refused !== undefined) {
    throw new EngineError(refused.code, refusalMessage(career, applicantId, refused));
  }
  const draft = cloneCareer(career);
  const applicant = applicantById(draft, applicantId);
  if (applicant === undefined) {
    throw new EngineError('InternalError', 'the Applicant left between the check and the offer');
  }

  const returning = applicant.formerHeroId !== undefined;
  const former = returning
    ? draft.guild.formerHeroes.find((hero) => hero.id === applicant.formerHeroId)
    : undefined;

  const joining: Hero = {
    id: applicant.id,
    name: applicant.name,
    pronouns: applicant.pronouns,
    stats: { ...applicant.stats },
    age: applicant.age,
    background: applicant.background,
    // `kind` travels with the Trait, in `clone.ts`'s key order: a timed Trait that arrives
    // without one is read as an Injury, so dropping it here would put somebody on the
    // Roster carrying an Injury they have not got (E6, DL-23 §10).
    traits: applicant.traits.map((trait) => {
      const carried: HeroTrait = { name: trait.name, since: trait.since };
      if (trait.liftsOn !== undefined) carried.liftsOn = trait.liftsOn;
      if (trait.kind !== undefined) carried.kind = trait.kind;
      return carried;
    }),
    // The calibre they applied at becomes the calibre they carry, so `HeroJoined.calibre`
    // and the field on the person are read off the same value and can never disagree (E5).
    calibre: applicant.calibre,
    regardForGuildmaster: {
      value: clamp(
        returning ? draft.config.returningRegard : draft.config.joiningRegard,
        draft.config.regardMin,
        draft.config.regardMax,
      ),
      reason: returning ? REASON_CAME_BACK : REASON_TAKEN_ON,
      nature: 'neutral',
    },
    // Somebody coming back remembers who they worked with; only the people who arrived
    // after they went are new to them (DL-19 §5).
    regardFor: {},
    joinedOn: draft.day,
    lastCommittedOn: draft.day,
    regardDecayedOn: draft.day,
  };
  if (applicant.formerHeroId !== undefined) joining.formerHeroId = applicant.formerHeroId;
  if (former !== undefined) {
    for (const [id, regard] of Object.entries(former.regardFor)) {
      joining.regardFor[id] = { value: regard.value, reason: regard.reason, nature: regard.nature };
    }
  }

  // The same six pieces of bookkeeping a Transfer, a Poaching and a Rival's retaliation
  // do — out of where they were, out of the Guild's record of people who left, onto the
  // Roster, Regard seeded both ways with `??=` so a remembered opinion survives, the
  // Guildmaster's own map filled, and E2's three timers set to today. Written once, in
  // `moveHero`, so the directions cannot drift apart (E5 §2, DL-20's "E5 must know").
  const hero = moveHero(
    draft,
    joining,
    { kind: 'applicants' },
    { kind: 'guild' },
    joining.regardForGuildmaster,
  ) as Hero;
  draft.ledger.applicantsAccepted += 1;
  // A reader takes `returners` to mean Heroes who CAME BACK, not offers made to one who
  // might not (finding C7) — so it is counted here, beside `applicantsAccepted`, and not
  // in `arriveApplicants` where `returnersOffered` is counted instead.
  if (applicant.formerHeroId !== undefined) draft.ledger.returners += 1;

  const events: GameEvent[] = [];
  events.push({
    type: 'ApplicantAccepted',
    day: draft.day,
    applicantId: applicant.id,
    heroId: hero.id,
    fee: applicant.askingFee,
    calibre: applicant.calibre,
  });
  changeCoin(draft, -applicant.askingFee, 'recruitment', events);
  events.push(
    hero.formerHeroId === undefined
      ? {
          type: 'HeroJoined',
          day: draft.day,
          heroId: hero.id,
          name: hero.name,
          calibre: hero.calibre,
          age: hero.age,
        }
      : {
          type: 'HeroJoined',
          day: draft.day,
          heroId: hero.id,
          name: hero.name,
          calibre: hero.calibre,
          age: hero.age,
          formerHeroId: hero.formerHeroId,
        },
  );
  return { career: draft, events };
}

/**
 * Send an Applicant away. It costs nothing but the Upkeep you did not take on (E4 §3).
 *
 * @throws EngineError `CareerEnded` or `NoSuchApplicant`.
 */
export function declineApplicant(career: Career, applicantId: string): Step {
  if (career.ended !== undefined) {
    throw new EngineError('CareerEnded', 'the Career has ended; there is nobody left to turn away');
  }
  const applicant = applicantById(career, applicantId);
  if (applicant === undefined) {
    throw new EngineError('NoSuchApplicant', `no Applicant with id "${applicantId}" is waiting`);
  }
  const draft = cloneCareer(career);
  draft.applicants = draft.applicants.filter((entry) => entry.id !== applicantId);
  return {
    career: draft,
    events: [
      {
        type: 'ApplicantDeclined',
        day: draft.day,
        applicantId,
        name: applicant.name,
        reason: 'player',
      },
    ],
  };
}

/** The message that goes with a rejection, so a thrown error reads as an explanation. */
function refusalMessage(career: Career, applicantId: string, refused: AcceptRefusal): string {
  switch (refused.code) {
    case 'CareerEnded':
      return 'the Career has ended; nobody else can be taken on';
    case 'NoSuchApplicant':
      return `no Applicant with id "${applicantId}" is waiting`;
    case 'RosterFull':
      return `the Roster is full at ${career.config.rosterCap}; nobody else can be taken on`;
    case 'InsufficientCoin':
      return `they ask ${applicantById(career, applicantId)?.askingFee ?? 0} coin and the Guild holds ${career.guild.coin}`;
    default: {
      const unreachable: never = refused.code;
      throw new EngineError('InternalError', `no message for ${String(unreachable)}`);
    }
  }
}
